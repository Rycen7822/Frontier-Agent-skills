#!/usr/bin/env python3
"""Render user-only ZCode commands from the canonical manual skills."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

import yaml

from _bundle_hash import MANUAL_SKILL_IDS, skill_source_path


ROOT = Path(__file__).resolve().parents[1]
COMMANDS = ROOT / ".zcode-plugin" / "commands"
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n(.*)\Z", re.DOTALL)
TEMPLATE_SYNTAX = re.compile(r"!`|^\s*```!|\$(?:ARGUMENTS|[0-9])", re.MULTILINE)


def render_command(skill_id: str) -> str:
    source = skill_source_path(skill_id)
    directory = ROOT / source
    match = FRONTMATTER.fullmatch((directory / "SKILL.md").read_text(encoding="utf-8"))
    if match is None:
        raise ValueError(f"missing skill frontmatter: {skill_id}")
    metadata, instructions = match.groups()
    description = json.dumps(yaml.safe_load(metadata)["description"], ensure_ascii=False)
    body = instructions.strip()
    references = sorted((directory / "references").glob("*.md"))
    if references:
        body += "\n\n## References for this command\n\nUse the following references only where the instructions call for them."
        for path in references:
            relative = path.relative_to(directory).as_posix()
            body = body.replace(f"]({relative})", f"](#{path.stem})")
            body += f"\n\n### {path.stem}\n\n{path.read_text(encoding='utf-8').strip()}"
    body = body.replace("](LICENSE)", f"](../../{source}/LICENSE)")
    if TEMPLATE_SYNTAX.search(body):
        raise ValueError(f"unexpected command expansion syntax in skill text: {skill_id}")

    return (
        f"---\ndescription: {description}\nargument-hint: '<request>'\n---\n\n"
        "<!-- Generated by scripts/build_zcode_commands.py; edit the source skill instead. -->\n\n"
        f"{body}\n\nUser request:\n$ARGUMENTS\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify without editing the command files")
    args = parser.parse_args()
    expected = {COMMANDS / f"{name}.md": render_command(name).encode("utf-8") for name in sorted(MANUAL_SKILL_IDS)}
    extras = set(COMMANDS.iterdir()) - expected.keys() if COMMANDS.is_dir() else set()
    if extras:
        parser.exit(1, f"Unexpected ZCode command files: {', '.join(sorted(p.name for p in extras))}\n")
    stale = [p for p, content in expected.items() if not p.is_file() or p.read_bytes() != content]
    if not stale:
        return 0
    if args.check:
        parser.exit(1, f"Run python3 scripts/build_zcode_commands.py to refresh: {', '.join(p.name for p in stale)}\n")
    COMMANDS.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_bytes(expected[path])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
